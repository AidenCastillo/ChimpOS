/* I/O port helper functions */
static inline void outb(uint16_t port, uint8_t value)
{
    __asm__ volatile("outb %0, %1" : : "a"(value), "Nd"(port));
}

static inline uint8_t inb(uint16_t port)
{
    uint8_t value;
    __asm__ volatile("inb %1, %0" : "=a"(value) : "Nd"(port));
    return value;
}

/* Switch back to text mode (mode 0x03 - 80x25 16-color text) */
void graphics_exit_to_text_mode(void)
{
    /* Step 1: Reset DAC mask to enable all palette entries for text mode */
    outb(0x3C6, 0xFF);  /* DAC mask register - all 8 bits */
    
    /* Step 2: Reset DAC write pointer to 0 */
    outb(0x3C8, 0x00);
    
    /* Step 3: Load standard VGA 16-color palette into DAC */
    /* Standard VGA palette (16 colors × 3 bytes RGB) */
    unsigned char pal[48] = {
        0x00, 0x00, 0x00,  /* 0: Black */
        0x00, 0x00, 0x2A,  /* 1: Blue */
        0x00, 0x2A, 0x00,  /* 2: Green */
        0x00, 0x2A, 0x2A,  /* 3: Cyan */
        0x2A, 0x00, 0x00,  /* 4: Red */
        0x2A, 0x00, 0x2A,  /* 5: Magenta */
        0x2A, 0x15, 0x00,  /* 6: Brown */
        0x2A, 0x2A, 0x2A,  /* 7: Light Gray */
        0x15, 0x15, 0x15,  /* 8: Dark Gray */
        0x15, 0x15, 0x3F,  /* 9: Light Blue */
        0x15, 0x3F, 0x15,  /* 10: Light Green */
        0x15, 0x3F, 0x3F,  /* 11: Light Cyan */
        0x3F, 0x15, 0x15,  /* 12: Light Red */
        0x3F, 0x15, 0x3F,  /* 13: Light Magenta */
        0x3F, 0x3F, 0x15,  /* 14: Yellow */
        0x3F, 0x3F, 0x3F   /* 15: White */
    };
    
    for (int i = 0; i < 48; i++) {
        outb(0x3C9, pal[i]);
    }
    
    /* Step 4: Set miscellaneous output for text mode */
    outb(0x3C2, 0x67);
    
    /* Step 5: Sequencer: reset and configure for text */
    outb(0x3C4, 0x00);  /* Reset register */
    outb(0x3C5, 0x03);
    
    outb(0x3C4, 0x01);  /* Clock mode register */
    outb(0x3C5, 0x00);
    
    outb(0x3C4, 0x02);  /* Map mask register */
    outb(0x3C5, 0x03);  /* All planes for text */
    
    outb(0x3C4, 0x03);  /* Character map select */
    outb(0x3C5, 0x00);
    
    outb(0x3C4, 0x04);  /* Memory mode register */
    outb(0x3C5, 0x02);  /* Text mode */
    
    /* Step 6: Graphics controller: text mode */
    outb(0x3CE, 0x00);  /* Set/Reset */
    outb(0x3CF, 0x00);
    
    outb(0x3CE, 0x01);  /* Set/Reset Enable */
    outb(0x3CF, 0x00);
    
    outb(0x3CE, 0x02);  /* Color Compare */
    outb(0x3CF, 0x00);
    
    outb(0x3CE, 0x03);  /* Data Rotate */
    outb(0x3CF, 0x00);
    
    outb(0x3CE, 0x04);  /* Read Map Select */
    outb(0x3CF, 0x00);
    
    outb(0x3CE, 0x05);  /* Mode register */
    outb(0x3CF, 0x00);  /* Text mode */
    
    outb(0x3CE, 0x06);  /* Miscellaneous */
    outb(0x3CF, 0x0E);  /* Framebuffer at 0xB8000 for text */
    
    /* Step 7: CRT Controller: text mode timings for 80x25 display */
    outb(0x3D4, 0x00);  outb(0x3D5, 0x5F);  /* Horizontal Total */
    outb(0x3D4, 0x01);  outb(0x3D5, 0x4F);  /* End Horizontal Display */
    outb(0x3D4, 0x02);  outb(0x3D5, 0x50);  /* Start Horizontal Blanking */
    outb(0x3D4, 0x03);  outb(0x3D5, 0x82);  /* End Horizontal Blanking */
    outb(0x3D4, 0x04);  outb(0x3D5, 0x55);  /* Start Horizontal Sync */
    outb(0x3D4, 0x05);  outb(0x3D5, 0x81);  /* End Horizontal Sync */
    outb(0x3D4, 0x06);  outb(0x3D5, 0xBF);  /* Vertical Total */
    outb(0x3D4, 0x07);  outb(0x3D5, 0x1F);  /* Overflow */
    outb(0x3D4, 0x08);  outb(0x3D5, 0x00);  /* Preset Row Scan */
    outb(0x3D4, 0x09);  outb(0x3D5, 0x0F);  /* Max Scan Line */
    outb(0x3D4, 0x0A);  outb(0x3D5, 0x0E);  /* Cursor Start Line */
    outb(0x3D4, 0x0B);  outb(0x3D5, 0x0F);  /* Cursor End Line */
    outb(0x3D4, 0x0C);  outb(0x3D5, 0x00);  /* Start Address High Byte */
    outb(0x3D4, 0x0D);  outb(0x3D5, 0x00);  /* Start Address Low Byte */
    outb(0x3D4, 0x0E);  outb(0x3D5, 0x00);  /* Cursor Location High */
    outb(0x3D4, 0x0F);  outb(0x3D5, 0x00);  /* Cursor Location Low */
    outb(0x3D4, 0x10);  outb(0x3D5, 0x9C);  /* Vertical Sync Start */
    outb(0x3D4, 0x11);  outb(0x3D5, 0x8E);  /* Vertical Sync End */
    outb(0x3D4, 0x12);  outb(0x3D5, 0x8F);  /* Vertical Display End */
    outb(0x3D4, 0x13);  outb(0x3D5, 0x28);  /* Offset/Logical Width */
    outb(0x3D4, 0x14);  outb(0x3D5, 0x1F);  /* Underline Location */
    outb(0x3D4, 0x15);  outb(0x3D5, 0x90);  /* Vertical Blank Start */
    outb(0x3D4, 0x16);  outb(0x3D5, 0xB9);  /* Vertical Blank End */
    outb(0x3D4, 0x17);  outb(0x3D5, 0xE3);  /* CRTC Mode Control */
    outb(0x3D4, 0x18);  outb(0x3D5, 0xFF);  /* Line Compare */
    
    /* Step 8: Reset attribute controller flip-flop and set palette */
    inb(0x3DA);  /* Reset flip-flop */
    
    /* Set all 16 attribute palette entries to pass-through (index = output) */
    for (int i = 0; i < 16; i++) {
        outb(0x3C0, i);
        outb(0x3C0, i);
    }
    
    /* Step 9: Set attribute controller mode register for text display */
    outb(0x3C0, 0x10);  /* Attribute Mode Control Register */
    outb(0x3C0, 0x00);  /* Text mode, no blink */
    
    /* Step 10: Set color select register */
    outb(0x3C0, 0x14);  /* Color Select Register */
    outb(0x3C0, 0x00);
    
    /* Step 11: Re-enable display */
    outb(0x3C0, 0x20);  /* Enable palette and display */
}

